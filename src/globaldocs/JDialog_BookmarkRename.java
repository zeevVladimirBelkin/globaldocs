    public JDialog_BookmarkRename(java.awt.Frame parent,String oldValue) {
        super(parent);
        initComponents();
        getRootPane().setDefaultButton(jButton_OK);
        
        Dimension sz=getSize();
        
        setLocation(
          (screenDimension.width-sz.width)>>1,
          (screenDimension.height-sz.height)>>1
        );
        
        String s=oldValue;
        
        if (s.length()>MAX_NAME_LENGTH)
          s=s.substring(0,MAX_NAME_LENGTH-5)+" ... ";
        
        jLabel_name.setText(
          jLabel_name.getText()+"\""+s+"\""
        );
        
        jTextField_rename.setText(oldValue);
        
        FocusGrabber.set(jTextField_rename);
        
        setVisible(true);
    }
    
    protected String getResult() {
      return accepted?nullify(jTextField_rename.getText()):null;
    }
    
    public static String invoke(String oldValue) {
      JDialog_BookmarkRename dlg=new JDialog_BookmarkRename(MainFrame.frame,oldValue);      
      String r=dlg.getResult();
      dlg.dispose();
      return r;
    }
    
